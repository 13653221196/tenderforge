def ensure_kb_templates() -> None:
    """知识库为空时放几条通用素材模板，新企业不至于打开一片空白。"""
    if not store.list_docs(scope="kb"):
        for title, content in KB_DOCS:
            store.add_doc(title, content, scope="kb")


def ensure_workspace() -> None:
    """新企业第一次建库：给知识库模板 + 一本空白标书，登录就能动手。"""
    ensure_kb_templates()
    if not store.list_projects():
        store.create_project("我的第一本标书", "")


def ensure_seed() -> None:
    ensure_kb_templates()
    # 归档的项目也算「已经有项目」：否则全部归档后一重启又冒出演示标书
    projects = store.list_projects(include_archived=True)
    demo = next((p for p in projects if "演示" in (p.get("name") or "")), None)
    if demo:
        # 演示项目被测试脚本清空过：补齐招标文件与本项目资料，保证各能力一打开就有效果
        pid = demo["id"]
        full = store.get_project(pid)
        if not (full.get("tender_text") or "").strip():
            store.update_project(pid, tender_text=TENDER)
        if not (full.get("materials") or []):
            for title, content in PROJECT_MATERIALS:
                store.add_doc(title, content, scope="project", project_id=pid)
        return
    if projects:
        return
    p = store.create_project("智慧园区视频监控系统采购（演示）", TENDER)
    pid = p["id"]
    for title, content in PROJECT_MATERIALS:
        store.add_doc(title, content, scope="project", project_id=pid)
    chapters = [{"title": t, "points": []} for t, _ in DRAFT_SECTIONS]
    store.update_project(pid, outline=chapters)
    store.set_sections(pid, chapters, replace_text=True)
    sections = store.list_sections(pid)
    by_title = {s["title"]: s for s in sections}
    for title, body in DRAFT_SECTIONS:
        sec = by_title.get(title)
        if sec:
            store.update_section(sec["id"], body, pid=pid)
